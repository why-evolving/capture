import Foundation

public struct LibraryEntry: Codable, Equatable, Identifiable, Sendable {
    public var id: UUID
    public var name: String
    public var favorite: Bool
    public var createdAt: Date
    public var modifiedAt: Date
    public var bytes: Int
    public init(project: CaptureProject, bytes: Int) {
        id = project.id; name = project.name; favorite = project.favorite
        createdAt = project.createdAt; modifiedAt = project.modifiedAt; self.bytes = bytes
    }
}
/// All calls must be serialized by the owner. Index entries contain UUIDs, never external paths.
public struct LibraryArchive: Sendable {
    public let directory: URL
    public var maximumCount = 32
    public var maximumBytes = 256 * 1024 * 1024
    public init(directory: URL) { self.directory = directory }
    private var indexURL: URL { directory.appendingPathComponent("index.json") }
    private func projectURL(_ id: UUID) -> URL { directory.appendingPathComponent(id.uuidString + ".capture") }
    private func thumbnailURL(_ id: UUID) -> URL { directory.appendingPathComponent(id.uuidString + ".png") }
    public func thumbnail(_ id: UUID) throws -> Data { try BoundedFile.read(thumbnailURL(id), limit: 1024 * 1024) }
    public func entries() throws -> [LibraryEntry] {
        guard FileManager.default.fileExists(atPath: indexURL.path) else { return [] }
        let result = try JSONDecoder().decode([LibraryEntry].self, from: BoundedFile.read(indexURL, limit: 1024 * 1024))
        guard result.count <= 1000, Set(result.map(\.id)).count == result.count,
              result.allSatisfy({ $0.name.count <= 200 && $0.bytes >= 0 && $0.bytes <= CaptureProject.maximumBytes + 1024 * 1024 && $0.modifiedAt.timeIntervalSince1970.isFinite }) else {
            throw CaptureFailure.persistence("历史索引损坏；项目文件仍保留")
        }
        return result.sorted { $0.modifiedAt > $1.modifiedAt }
    }
    public func read(_ id: UUID) throws -> CaptureProject {
        let project = try CaptureProject.read(projectURL(id))
        guard project.id == id else { throw CaptureFailure.persistence("历史项目身份不匹配") }
        return project
    }
    @discardableResult public func save(_ project: CaptureProject, retentionDays: Int, now: Date = Date()) throws -> [LibraryEntry] {
        guard [7,30].contains(retentionDays), maximumCount > 0, maximumBytes > 0 else { throw CaptureFailure.invalidImage }
        let data = try project.encoded()
        guard data.count <= maximumBytes else { throw CaptureFailure.imageTooLarge }
        var thumbnailData: Data?
        if let source = try? project.image(), let content = try? EditedImageRenderer.render(source, edits: project.edits),
           let preview = try? StyleCompositor.render(content, style: project.useStyle ? project.style : nil, previewLimit: 300) { thumbnailData = try? StyleCompositor.encode(preview) }
        let totalBytes = data.count + (thumbnailData?.count ?? 0)
        guard totalBytes <= maximumBytes else { throw CaptureFailure.imageTooLarge }
        var list = try entries().filter { $0.id != project.id }
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        try data.write(to: projectURL(project.id), options: .atomic)
        if let thumbnailData { try thumbnailData.write(to: thumbnailURL(project.id), options: .atomic) }
        list.append(LibraryEntry(project: project, bytes: totalBytes))
        return try prune(list, retentionDays: retentionDays, now: now)
    }
    @discardableResult public func prune(retentionDays: Int, now: Date = Date()) throws -> [LibraryEntry] {
        try prune(entries(), retentionDays: retentionDays, now: now)
    }
    private func prune(_ list: [LibraryEntry], retentionDays: Int, now: Date) throws -> [LibraryEntry] {
        guard [7,30].contains(retentionDays), maximumCount > 0, maximumBytes > 0 else { throw CaptureFailure.invalidImage }
        let cutoff = now.addingTimeInterval(-Double(retentionDays) * 86400)
        var kept: [LibraryEntry] = [], bytes = 0
        for entry in list.sorted(by: { $0.modifiedAt > $1.modifiedAt }) {
            if entry.modifiedAt >= cutoff && kept.count < maximumCount && entry.bytes <= maximumBytes - bytes && FileManager.default.fileExists(atPath: projectURL(entry.id).path) {
                kept.append(entry); bytes += entry.bytes
            }
        }
        try writeIndex(kept)
        for entry in list where !kept.contains(where: { $0.id == entry.id }) { try removeFile(entry.id) }
        return kept
    }
    public func remove(_ id: UUID) throws {
        try writeIndex(entries().filter { $0.id != id }); try removeFile(id)
    }
    public func clear() throws {
        // Only names generated by this archive are eligible; unrelated files survive.
        let urls = (try? FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)) ?? []
        try writeIndex([])
        for url in urls where ["capture", "png"].contains(url.pathExtension) {
            if let id = UUID(uuidString: url.deletingPathExtension().lastPathComponent), url.lastPathComponent == id.uuidString + "." + url.pathExtension { try removeFile(id) }
        }
    }
    private func writeIndex(_ entries: [LibraryEntry]) throws {
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        try JSONEncoder().encode(entries).write(to: indexURL, options: .atomic)
    }
    private func removeFile(_ id: UUID) throws {
        let url = projectURL(id)
        if FileManager.default.fileExists(atPath: url.path) { try FileManager.default.removeItem(at: url) }
        let thumbnail = thumbnailURL(id)
        if FileManager.default.fileExists(atPath: thumbnail.path) { try FileManager.default.removeItem(at: thumbnail) }
    }
}
